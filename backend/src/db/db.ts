import { randomUUID } from 'node:crypto';
import { AsyncLocalStorage } from 'node:async_hooks';
import { Pool, type PoolClient, types } from 'pg';
import { hashPassword } from '../auth/password';

// Neon Postgres. DATABASE_URL is in backend/.env locally and in the host's env vars in production.
const url = process.env.DATABASE_URL;
if (!url) throw new Error('DATABASE_URL is not set. Add the Neon connection string to backend/.env.');

// BIGINT counts and ids come back as numbers, as they did from SQLite.
types.setTypeParser(20, (v) => Number(v));

export const pool = new Pool({ connectionString: url, max: 5 });

// Inside inTransaction every query runs on the transaction's client. Outside it, the pool.
const txStore = new AsyncLocalStorage<PoolClient>();
const runner = () => txStore.getStore() ?? pool;

export async function query<T = Record<string, unknown>>(text: string, params: unknown[] = []): Promise<T[]> {
  return (await runner().query(text, params)).rows as T[];
}

export async function one<T = Record<string, unknown>>(text: string, params: unknown[] = []): Promise<T | undefined> {
  return (await query<T>(text, params))[0];
}

// For writes. Returns the affected row count.
export async function run(text: string, params: unknown[] = []): Promise<number> {
  return (await runner().query(text, params)).rowCount ?? 0;
}

export async function inTransaction<T>(fn: () => Promise<T>): Promise<T> {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const out = await txStore.run(client, fn);
    await client.query('COMMIT');
    return out;
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
}

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,
  name TEXT NOT NULL,
  roll_no TEXT NOT NULL DEFAULT '',
  college TEXT NOT NULL DEFAULT '',
  branch TEXT NOT NULL DEFAULT 'Mechanical Engineering',
  semester INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'teacher'))
);
CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS recordings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  experiment_id TEXT NOT NULL,
  data TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS activities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type TEXT NOT NULL,
  experiment_id TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_recordings_user ON recordings(user_id, experiment_id);
CREATE INDEX IF NOT EXISTS idx_activities_user ON activities(user_id, created_at);
CREATE TABLE IF NOT EXISTS vivas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  experiment_id TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('draft', 'published', 'closed')),
  created_at TEXT NOT NULL,
  published_at TEXT
);
CREATE TABLE IF NOT EXISTS viva_questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  viva_id BIGINT NOT NULL REFERENCES vivas(id) ON DELETE CASCADE,
  position INTEGER NOT NULL,
  data TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS viva_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  viva_id BIGINT NOT NULL REFERENCES vivas(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status TEXT NOT NULL CHECK (status IN ('in_progress', 'submitted')),
  started_at TEXT NOT NULL,
  submitted_at TEXT,
  score DOUBLE PRECISION,
  pending_review INTEGER NOT NULL DEFAULT 0,
  UNIQUE (viva_id, user_id)
);
CREATE TABLE IF NOT EXISTS viva_answers (
  attempt_id BIGINT NOT NULL REFERENCES viva_attempts(id) ON DELETE CASCADE,
  question_id BIGINT NOT NULL,
  answer TEXT,
  correct INTEGER,
  score DOUBLE PRECISION,
  PRIMARY KEY (attempt_id, question_id)
);
CREATE INDEX IF NOT EXISTS idx_vivas_teacher ON vivas(teacher_id);
CREATE INDEX IF NOT EXISTS idx_viva_questions_viva ON viva_questions(viva_id, position);
`;

// Creates the tables and seeds the demo student. Called once before the server listens.
export async function initDatabase(): Promise<void> {
  await pool.query(SCHEMA);
  // The oral interview keeps its transcript on the attempt, and each answer keeps the AI's feedback.
  await pool.query('ALTER TABLE viva_attempts ADD COLUMN IF NOT EXISTS transcript TEXT');
  await pool.query('ALTER TABLE viva_answers ADD COLUMN IF NOT EXISTS feedback TEXT');

  // Demo student for trying the app locally. Off unless SEED_DEMO_ACCOUNTS=true, so a public deploy has no known login.
  if (process.env.SEED_DEMO_ACCOUNTS === 'true') {
    await pool.query(
      `INSERT INTO users (id, email, password_hash, name, roll_no, college, branch, semester, created_at)
       SELECT $1::text, $2::text, $3::text, $4::text, $5::text, $6::text, $7::text, $8::int, $9::text
       WHERE NOT EXISTS (SELECT 1 FROM users)`,
      [
        randomUUID(),
        'student@simvaya.lab',
        hashPassword('simvaya-demo'),
        'Arjun Kumar',
        'MECH-2023-041',
        'Demo Institute of Technology',
        'Mechanical Engineering',
        6,
        new Date().toISOString(),
      ],
    );
  }
}
